"""Declarative base and column helpers shared by all tables."""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Index/FK/PK names are generated deterministically from this convention. Unique and CHECK
# constraints are named explicitly where they are declared.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key generated by PostgreSQL, so rows created by any writer get one."""
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


def utc_now_column() -> Mapped[datetime]:
    """timestamptz defaulting to the database clock. The connection timezone is pinned to UTC."""
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
